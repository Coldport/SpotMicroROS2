"""
Minimal register-level I2C driver for the Bosch BNO055 9-DOF IMU
(Adafruit breakout https://www.adafruit.com/product/2472).

Talks I2C directly via smbus2 rather than pulling in the full
adafruit-blinka/CircuitPython stack. That matters here specifically because
ROS2 console-script entry points (what `ros2 run`/`ros2 launch` execute) are
generated by colcon with a shebang baked to whatever python3 colcon itself
runs under — the system python3, regardless of whether this repo's .venv is
active at build or run time — so a dependency only pip-installed into .venv
would not be importable by the node. smbus2 sidesteps that: it's a plain apt
package (python3-smbus2, installed by setup.sh) that lands in the system
python3's site-packages.

Register map, scale factors, and startup sequence are from the Bosch BNO055
datasheet (rev 1.7), section 4.2 (register map) and 3.6.5 (data output units).
"""

import time

from smbus2 import SMBus

_CHIP_ID_REG = 0x00
_EXPECTED_CHIP_ID = 0xA0

_PAGE_ID = 0x07
_MAG_DATA = 0x0E
_GYR_DATA = 0x14
_QUA_DATA = 0x20
_LIA_DATA = 0x28   # linear acceleration: gravity-compensated
_TEMP = 0x34
_CALIB_STAT = 0x35
_SYS_TRIGGER = 0x3F
_UNIT_SEL = 0x3B
_OPR_MODE = 0x3D
_PWR_MODE = 0x3E

_MODE_CONFIG = 0x00
_MODE_NDOF = 0x0C   # full sensor fusion, all axes, fast magnetometer calibration
_POWER_NORMAL = 0x00

# UNIT_SEL bit1 = 1 selects gyroscope output in rad/s instead of the default
# deg/s. Everything else is left at its power-on default (accelerometer
# m/s^2, temperature Celsius); Euler-angle units don't matter since this
# driver only reads the quaternion.
_UNIT_SEL_GYRO_RPS = 0x02

_BOOT_DELAY_S = 0.65     # datasheet: worst-case power-on boot time
_MODE_SWITCH_DELAY_S = 0.025   # datasheet: max 19ms to switch operation mode


class Bno055:
    """Reads fused orientation/gyro/accel/mag/temperature from a BNO055."""

    def __init__(self, bus_num=1, address=0x28):
        self._address = address
        self._bus = SMBus(bus_num)

        time.sleep(_BOOT_DELAY_S)
        chip_id = self._bus.read_byte_data(self._address, _CHIP_ID_REG)
        if chip_id != _EXPECTED_CHIP_ID:
            raise RuntimeError(
                f'Unexpected chip ID 0x{chip_id:02x} at I2C address 0x{address:02x} '
                f'(expected 0x{_EXPECTED_CHIP_ID:02x} for a BNO055)')

        self._write(_OPR_MODE, _MODE_CONFIG)
        time.sleep(_MODE_SWITCH_DELAY_S)
        self._write(_PAGE_ID, 0x00)
        self._write(_SYS_TRIGGER, 0x00)   # use the internal oscillator
        self._write(_PWR_MODE, _POWER_NORMAL)
        self._write(_UNIT_SEL, _UNIT_SEL_GYRO_RPS)
        self._write(_OPR_MODE, _MODE_NDOF)
        time.sleep(_MODE_SWITCH_DELAY_S)

    def _write(self, register, value):
        self._bus.write_byte_data(self._address, register, value)

    def _read_signed16_block(self, register, count):
        raw = self._bus.read_i2c_block_data(self._address, register, count * 2)
        values = []
        for i in range(count):
            v = raw[2 * i] | (raw[2 * i + 1] << 8)
            if v >= 0x8000:
                v -= 0x10000
            values.append(v)
        return values

    def read_quaternion(self):
        """(w, x, y, z), unit quaternion."""
        w, x, y, z = self._read_signed16_block(_QUA_DATA, 4)
        scale = 1.0 / (1 << 14)   # Q14 format: 2^14 LSB per unit quaternion
        return (w * scale, x * scale, y * scale, z * scale)

    def read_gyro(self):
        """(x, y, z), rad/s."""
        x, y, z = self._read_signed16_block(_GYR_DATA, 3)
        scale = 1.0 / 900.0   # 900 LSB per rad/s (UNIT_SEL set to rps in __init__)
        return (x * scale, y * scale, z * scale)

    def read_linear_acceleration(self):
        """(x, y, z), m/s^2, with gravity subtracted out."""
        x, y, z = self._read_signed16_block(_LIA_DATA, 3)
        scale = 1.0 / 100.0   # 100 LSB per m/s^2
        return (x * scale, y * scale, z * scale)

    def read_magnetic(self):
        """(x, y, z), microtesla."""
        x, y, z = self._read_signed16_block(_MAG_DATA, 3)
        scale = 1.0 / 16.0   # 16 LSB per microtesla
        return (x * scale, y * scale, z * scale)

    def read_temperature(self):
        """Onboard die temperature, degrees Celsius."""
        raw = self._bus.read_byte_data(self._address, _TEMP)
        if raw >= 0x80:
            raw -= 0x100
        return float(raw)   # 1 LSB = 1 degree C

    def read_calibration_status(self):
        """(sys, gyro, accel, mag), each 0 (uncalibrated) - 3 (fully calibrated)."""
        status = self._bus.read_byte_data(self._address, _CALIB_STAT)
        sys_cal = (status >> 6) & 0x03
        gyro_cal = (status >> 4) & 0x03
        accel_cal = (status >> 2) & 0x03
        mag_cal = status & 0x03
        return (sys_cal, gyro_cal, accel_cal, mag_cal)
